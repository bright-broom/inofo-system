/* ---------------------------------------------------------------- 使い方と目次 */
const intro = [
  box("困ったときは", [
    "1.　まず、このFAQで探してください（目次から探せます）。",
    "2.　解決しないときは、ITサポートに連絡してください：〔チャットのチャンネル名〕〔メールアドレス〕",
    `3.　ITサポートの対応時間は ${HOURS} です。急ぎ・事故の疑いは〔A様〕に電話してください。`,
  ]),
  blank(),
  p("目次", { bold: true, size: 26 }),
  ...FAQ.flatMap(([cat, qs], ci) => [
    p(`${ci + 1}. ${cat}`, { bold: true, before: 120, after: 40 }),
    ...qs.map(([q], qi) => p(`Q${ci + 1}-${qi + 1}　${q}`, { indent: { left: 420 }, after: 20, size: 19 })),
  ]),
  new Paragraph({ children: [new PageBreak()] }),
];

/* ---------------------------------------------------------------- 本文 */
function answer(line: string) {
  if (line.startsWith("・")) return bullet(line.slice(1));
  if (line.startsWith("→")) return p(`関連：${line.slice(1).trim()}`, { color: MUTED, size: 19, indent: { left: 420 } });
  return p(line, { indent: { left: 420 } });
}

const body = FAQ.flatMap(([cat, qs], ci) => [
  h1(String(ci + 1), cat),
  ...qs.flatMap(([q, lines], qi) => [
    new Paragraph({
      keepNext: true,
      spacing: { before: 240, after: 80 },
      children: [run(`Q${ci + 1}-${qi + 1}　`, { bold: true, color: INDIGO, size: 23 }), run(q, { bold: true, size: 23 })],
    }),
    ...lines.map(answer),
  ]),
]);

/* ---------------------------------------------------------------- 更新の記録 */
